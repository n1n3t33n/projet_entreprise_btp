Inventaire inventaireDemo(List<ArticleStock> articles) {
  const codes = [
    'BOI-400',
    'FER-012',
    'GRA-1525',
    'TRL-003',
    'CIM-045',
    'FER-014',
  ];
  final lignes = <LigneInventaire>[];
  for (final code in codes) {
    final article = articles.firstWhere((a) => a.code == code);
    final ligne = LigneInventaire(
      codeArticle: article.code,
      designation: article.designation,
      unite: article.unite,
      emplacement: article.emplacement,
      theorique: article.quantite,
    );
    lignes.add(
      code == 'BOI-400' ? ligne.comptee(article.quantite, null) : ligne,
    );
  }
  return Inventaire(
    id: 'INV-2026-05',
    zone: 'Zone A — Gros œuvre',
    lignes: lignes,
    statut: StatutInventaire.enCours,
  );
}

